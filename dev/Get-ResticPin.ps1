<#
.SYNOPSIS
    Prints the Get-ResticPin function for Restic-ManageSnapshots.ps1, for a restic release.

.DESCRIPTION
    Development helper, not used at runtime. Downloads the Windows zips of a restic release
    and its SHA256SUMS, checks the zips against SHA256SUMS, extracts the exes and
    prints the function with the zip and exe hashes. Replace Get-ResticPin in the script with it.

    SHA256SUMS comes from the same release, so this checks the downloads, not the release itself.
    To verify the release, check SHA256SUMS.asc with the restic maintainers' GPG key first.

.PARAMETER Version
    The restic version, e.g. 0.19.1. Default: the latest release.

.PARAMETER Architectures
    Windows builds to pin. restic ships no Windows arm64 build (0.19.1: amd64 and 386 only).
#>
[CmdletBinding()]
param([string]$Version, [string[]]$Architectures = @('amd64'))

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
Add-Type -AssemblyName System.IO.Compression.FileSystem

if (-not $Version) {
    $release = Invoke-RestMethod -Uri 'https://api.github.com/repos/restic/restic/releases/latest' -UseBasicParsing
    $Version = $release.tag_name.TrimStart('v')
}
$Version = $Version.TrimStart('v')
$base = "https://github.com/restic/restic/releases/download/v$Version"

$work = Join-Path ([System.IO.Path]::GetTempPath()) "restic-pin-$Version-$([guid]::NewGuid().ToString('N'))"
New-Item -ItemType Directory -Path $work | Out-Null
try {
    $sumsPath = Join-Path $work 'SHA256SUMS'
    Invoke-WebRequest -Uri "$base/SHA256SUMS" -OutFile $sumsPath -UseBasicParsing
    $sums = @{}
    foreach ($line in Get-Content -LiteralPath $sumsPath) {
        if ($line -match '^([0-9a-fA-F]{64})\s+\*?(\S+)$') { $sums[$Matches[2]] = $Matches[1].ToUpper() }
    }

    $files = [ordered]@{}
    foreach ($arch in $Architectures) {
        $zipName = "restic_${Version}_windows_$arch.zip"
        $exeName = "restic_${Version}_windows_$arch.exe"
        if (-not $sums.ContainsKey($zipName)) { throw "$zipName is not listed in SHA256SUMS." }

        $zipPath = Join-Path $work $zipName
        Write-Host "Downloading $zipName"
        Invoke-WebRequest -Uri "$base/$zipName" -OutFile $zipPath -UseBasicParsing
        $zipHash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash
        if ($zipHash -ne $sums[$zipName]) { throw "$zipName doesn't match SHA256SUMS." }

        $exePath = Join-Path $work $exeName
        $archive = [System.IO.Compression.ZipFile]::OpenRead($zipPath)
        try {
            $entry = $archive.Entries | Where-Object { $_.FullName -eq $exeName } | Select-Object -First 1
            if (-not $entry) { throw "$zipName doesn't contain $exeName." }
            [System.IO.Compression.ZipFileExtensions]::ExtractToFile($entry, $exePath, $true)
        }
        finally { $archive.Dispose() }

        $files[$arch] = @{ Zip = $zipHash; Exe = (Get-FileHash -LiteralPath $exePath -Algorithm SHA256).Hash }
    }
}
finally {
    Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
}

$lines = @(
    "# The restic release Setup installs into <dataDirectory>\bin. Generated by dev\Get-ResticPin.ps1 -Version $Version."
    'function Get-ResticPin {'
    '    return @{'
    "        Version = '$Version'"
)
foreach ($arch in $files.Keys) {
    $lines += "        $arch = @{ Zip = '$($files[$arch].Zip)'; Exe = '$($files[$arch].Exe)' }"
}
$lines += @('    }', '}')

Write-Host ''
$lines | ForEach-Object { Write-Output $_ }
